export function getFleetKpis(robots: FleetRobot[], orders: FleetWorkOrder[]): FleetKpis {
  const online = robots.filter((r) => r.online).length
  const inboundBusy = robots.filter(
    (r) => r.role === 'inbound' && (r.status === 'operating' || r.status === 'navigating'),
  ).length
  const outboundBusy = robots.filter(
    (r) => r.role === 'outbound' && (r.status === 'operating' || r.status === 'navigating'),
  ).length
  const activeOrders = orders.filter((o) => o.status === 'in_progress' || o.status === 'pending').length
  const todayDelivered = orders.reduce((s, o) => s + o.deliveredTrays, 0)
  return {
    online,
    total: robots.length,
    inboundBusy,
    outboundBusy,
    activeOrders,
    todayDelivered,
  }
}
